// Writes src/components/bench/manifest.js: which figs-*.jsx file holds each bench
// diagram id, so a lesson loads only the file it needs instead of every diagram.
// Run by check-data.mjs, so `npm test` and every build keep it current.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'src/components/bench')

export function benchManifest() {
  const fileOf = {}
  for (const f of fs.readdirSync(dir).filter((f) => /^figs-.*\.jsx$/.test(f)).sort()) {
    const src = fs.readFileSync(path.join(dir, f), 'utf8')
    for (const m of src.matchAll(/^\s{2}'([a-z0-9-]+)':\s*[A-Z]\w*,?\s*$/gm)) fileOf[m[1]] = f.slice(5, -4)
  }
  const out =
    '// Generated by scripts/bench-manifest.mjs. Do not edit by hand.\n' +
    `export const FILE_OF = ${JSON.stringify(fileOf, null, 0).replace(/,"/g, ',\n  "').replace('{"', '{\n  "').replace(/}$/, '\n}')}\n`
  const target = path.join(dir, 'manifest.js')
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out) fs.writeFileSync(target, out)
  return fileOf
}

if (process.argv[1] === fileURLToPath(import.meta.url)) console.log(`${Object.keys(benchManifest()).length} bench diagrams`)
